"""Correctness suite: assert the current code reproduces upstream's numerics.

The fixtures in `tests/fixtures/golden.pt` were generated by running the
*original upstream implementation* (see `tests/generate_fixtures.py` for the
exact procedure and for what is deliberately out of scope). This module replays
the recorded inputs through the current code and compares against the recorded
outputs, one test per recorded case.

Each case checks two things in order:

1. **Parameter checksum.** Weights are rebuilt from a fixed seed rather than
   stored, so if module construction changes -- a new layer, a reordered
   `nn.Module` attribute, a different init -- the weights differ and every
   output would differ too. Checking the checksum first turns that into a clear
   "initialisation changed" failure instead of a confusing numerical one.
2. **Outputs**, via `torch.testing.assert_close` at a tight but non-bitwise
   tolerance. Bitwise equality is not asserted because einsum/bmm may pick
   different reduction orders depending on tensor contiguity.

Every case runs on each available execution path -- CPU vanilla, CUDA vanilla,
CUDA with the fused cuEquivariance kernels -- against the same goldens, at a
tolerance chosen per path. One reference for all three is the point: comparing
the fused kernels against our own PyTorch fallback would only establish that
two of our implementations agree, which is the weaker claim.

The CUDA paths skip on a machine without a GPU, so locally this suite is still
a single-path CPU run.

A missing `golden.pt` is a **collection error**, not a skip: the suite cannot
report green without it, because "no goldens" is indistinguishable from "no
regressions" to everything downstream.

    pytest tests/test_correctness.py
"""

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import pytest
import torch

from bench.step import CUEQUIVARIANCE_PRESENT, triangle_path
from tests.generate_fixtures import build_cases, compare_fingerprints, param_fingerprint

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "golden.pt"
PACKAGE = "msa_pairformer"

# Tolerances are per execution path, because the paths do not agree to the same
# precision and pretending otherwise means either false failures or a test that
# cannot detect anything.
#
# Measured, not guessed: bench/results/h100-drift.json, H100 80GB, torch
# 2.13.0+cu130, TF32 off. Worst absolute deviation from the goldens per path:
#
#     cpu/vanilla    1.287e-05      cuda/vanilla   1.246e-05
#     cuda/cuex      1.246e-05      (identical to cuda/vanilla -- see below)
#
# On the machine that recorded the goldens, cpu/vanilla is exactly 0.0. It is
# not zero anywhere else, and that is the constraint these numbers are sized
# for: the same 1-ULP initialisation differences that motivated
# `param_fingerprint` propagate through the forward pass, reaching ~1.3e-5 on
# the 22-layer model. A tolerance tight enough to be exact on one machine makes
# the suite unrunnable on every other, which is where it matters most.
#
# All three rows carry the same numbers because the fixtures are recorded at
# N=10, and cuEquivariance declines shapes that small -- so the cuex row here
# measures the fallback, not the fused kernels. That is a known limit of this
# file rather than a claim about the kernels; tests/test_cuequivariance.py
# covers them at N=312, where they demonstrably engage.
TOLERANCES: dict[str, tuple[float, float]] = {
    # path: (rtol, atol)
    "cpu/vanilla": (1e-4, 5e-5),
    "cuda/vanilla": (1e-4, 5e-5),
    "cuda/cuex": (1e-4, 5e-5),
}


@dataclass(frozen=True)
class ExecutionPath:
    """One device and triangle implementation, replayed against the goldens.

    The path is part of how cases are *built*, not a setting applied around
    them. `PairwiseBlock` and `MSAPairformer` read `CUEQUIVARIANCE_AVAILABLE`
    when they construct their submodules, and construction happens inside the
    case callable -- so both `build_cases` and the call it returns have to sit
    inside the context, exactly as `bench/drift.py` does it.

    Reusing a registry built once across several paths would silently defeat
    this: conftest forces vanilla for the whole session, so a `cuda/cuex` case
    drawing from that registry would compare vanilla output against vanilla
    goldens and pass while testing nothing.
    """

    device: torch.device
    cuequivariance: bool

    @property
    def label(self) -> str:
        return f"{self.device.type}/{'cuex' if self.cuequivariance else 'vanilla'}"

    @property
    def tolerance(self) -> tuple[float, float]:
        return TOLERANCES[self.label]

    def replay(self, name: str):
        with triangle_path(self.cuequivariance) as effective:
            assert effective == self.cuequivariance, (
                f"{self.label}: asked for cuequivariance={self.cuequivariance} "
                f"but got {effective}. The fixture should have skipped."
            )
            cases = dict(
                build_cases(PACKAGE, device=self.device, use_cuequivariance=effective)
            )
            return cases[name]()


PATHS = [
    ExecutionPath(torch.device("cpu"), False),
    ExecutionPath(torch.device("cuda"), False),
    ExecutionPath(torch.device("cuda"), True),
]


@pytest.fixture(params=PATHS, ids=lambda p: p.label)
def path(request) -> ExecutionPath:
    p: ExecutionPath = request.param
    if p.device.type == "cuda" and not torch.cuda.is_available():
        pytest.skip("needs a CUDA host")
    if p.cuequivariance and not CUEQUIVARIANCE_PRESENT:
        pytest.skip("needs cuequivariance_torch")
    return p

# Cases whose loss would gut the suite. Named explicitly so that a parametrise
# or fixture-generation bug that silently collects fewer cases fails loudly
# instead of passing with a smaller test count.
REQUIRED_CASES = {
    "core.Transition",
    "pairwise_operations.MSAPairWeightedAveraging",
    "pairwise_operations.TriangleMultiplication[outgoing]",
    "pairwise_operations.TriangleMultiplication[incoming]",
    "outer_product.OuterProduct[presoftmax_differential]",
    "model.MSAPairformer.forward",
}


@lru_cache(maxsize=1)
def load_fixture():
    if not FIXTURE_PATH.exists():
        raise FileNotFoundError(
            f"{FIXTURE_PATH} is missing. Regenerate it from the upstream tree; "
            "see the docstring in tests/generate_fixtures.py."
        )
    return torch.load(FIXTURE_PATH, weights_only=False)


def recorded_case_names():
    """Parametrisation source, evaluated at collection time."""
    return sorted(load_fixture()["cases"])


def test_every_recorded_case_has_a_generator():
    """Checked once rather than per case: a fixture entry with no generator is a
    fixture/code mismatch, not a numerical failure of any one path."""
    missing = set(load_fixture()["cases"]) - set(dict(build_cases(PACKAGE)))
    assert not missing, f"fixture has cases with no generator: {sorted(missing)}"


@pytest.mark.parametrize("name", recorded_case_names())
def test_case_matches_upstream(path: ExecutionPath, name):
    expected = load_fixture()["cases"][name]
    module, _inputs, actual = path.replay(name)
    rtol, atol = path.tolerance

    # Path-independent by construction: the fused and vanilla triangle paths
    # share one set of parameters and differ only in `forward`, so a mismatch
    # here is always a change to initialisation, never a change of kernel.
    problems = compare_fingerprints(
        param_fingerprint(module), expected["param_fingerprint"]
    )
    assert not problems, (
        f"{name}: module initialisation changed --\n  "
        + "\n  ".join(problems)
        + "\nOutputs cannot be meaningfully compared; if this change is "
        "intentional, regenerate the fixtures."
    )

    assert set(actual) == set(expected["outputs"]), (
        f"{name}: output keys changed: {sorted(actual)} != "
        f"{sorted(expected['outputs'])}"
    )

    for key, want in expected["outputs"].items():
        have = actual[key]
        if want is None:
            assert have is None, f"{name}.{key}: expected None, got a tensor"
            continue
        assert have.shape == want.shape, (
            f"{name}.{key}: shape {tuple(have.shape)} != {tuple(want.shape)}"
        )
        # The goldens were recorded on CPU; move them rather than the output, so
        # a GPU result is never rounded on its way to the comparison.
        torch.testing.assert_close(
            have, want.to(have.device), rtol=rtol, atol=atol,
            msg=lambda m, _n=name, _k=key, _p=path.label:
                f"{_n}.{_k} diverged from upstream on {_p}:\n{m}",
        )


def test_fingerprint_tolerates_last_bit_noise_but_not_a_real_change():
    """The fingerprint replaced an exact hash, so it has to earn both halves.

    Too tight and it fails on the 1-ULP cross-architecture differences that
    motivated the change; too loose and it stops detecting the thing it exists
    to detect. This pins both ends rather than trusting the tolerance to be
    well chosen.
    """
    torch.manual_seed(0)
    module = torch.nn.Linear(64, 64)
    baseline = param_fingerprint(module)

    with torch.no_grad():
        ulp = torch.finfo(torch.float32).eps * module.weight.abs().clamp_min(1e-6)
        module.weight += ulp
    assert not compare_fingerprints(param_fingerprint(module), baseline), (
        "a one-ULP perturbation trips the fingerprint, which is the failure "
        "mode it was introduced to remove"
    )

    with torch.no_grad():
        module.weight[0, 0] += 0.5
    problems = compare_fingerprints(param_fingerprint(module), baseline)
    assert problems, "a single changed weight goes undetected"
    assert any("weight" in p for p in problems), problems

    torch.manual_seed(0)
    wider = torch.nn.Linear(64, 128)
    shape_problems = compare_fingerprints(param_fingerprint(wider), baseline)
    assert any("shape" in p for p in shape_problems), shape_problems


def test_fixture_covers_the_core_stack():
    """Guard against the suite silently shrinking to a trivial subset."""
    missing = REQUIRED_CASES - set(load_fixture()["cases"])
    assert not missing, f"fixture no longer covers: {sorted(missing)}"


def test_fixture_came_from_upstream():
    """The goldens are only meaningful if they were recorded from the original
    implementation, not regenerated from the code under test."""
    meta = load_fixture()["metadata"]
    assert meta["source_package"] == "MSA_Pairformer", (
        f"fixtures were generated from {meta['source_package']!r}, not the "
        "upstream package. They pin current behaviour rather than upstream's."
    )
